def _get_input_shape(graph: GraphSchema) -> list[int]:
    """Extract input shape from the graph's input node."""
    for n in graph.nodes:
        if n.type == "input":
            shape = n.params.get("shape")
            if isinstance(shape, list) and len(shape) > 0:
                return [int(x) for x in shape]
    return [1, 28, 28]


def _get_num_classes(graph: GraphSchema, shapes: dict) -> int:
    """Infer number of output classes from the last Linear layer's out_features."""
    topo = topological_sort(graph)
    nodes_by_id = {n.id: n for n in graph.nodes}
    last_linear_out = 10
    for nid in topo:
        node = nodes_by_id[nid]
        if node.type == "linear":
            last_linear_out = int(node.params.get("out_features", 128))
    return last_linear_out


def _generate_model_code(graph: GraphSchema, shapes: dict) -> str:
    """Generate clean, readable model.py code from the visual graph."""
    topo = topological_sort(graph)
    nodes_by_id = {n.id: n for n in graph.nodes}
    input_shape = _get_input_shape(graph)

    imports = [
        '"""',
        "Model architecture generated by JulyAI.",
        f"Generated on: {datetime.utcnow().strftime('%Y-%m-%d %H:%M:%S UTC')}",
        '"""',
        "",
        "import math",
        "import torch",
        "import torch.nn as nn",
        "",
    ]

    # Collect helper classes needed
    needs_positional_encoding = any(
        nodes_by_id[nid].type == "positional_encoding" for nid in topo
    )
    needs_positional_embedding = any(
        nodes_by_id[nid].type == "positional_embedding" for nid in topo
    )

    helper_classes = []
    if needs_positional_encoding:
        helper_classes.append('''
class PositionalEncoding(nn.Module):
    """Sinusoidal positional encoding (Vaswani et al.)."""

    def __init__(self, d_model: int, max_len: int = 512, dropout: float = 0.0):
        super().__init__()
        self.dropout = nn.Dropout(p=dropout)
        pe = torch.zeros(max_len, d_model)
        position = torch.arange(0, max_len, dtype=torch.float).unsqueeze(1)
        div_term = torch.exp(
            torch.arange(0, d_model, 2).float() * (-math.log(10000.0) / d_model)
        )
        pe[:, 0::2] = torch.sin(position * div_term)
        pe[:, 1::2] = torch.cos(position * div_term)
        self.register_buffer("pe", pe.unsqueeze(0))

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        seq_len = x.size(1)
        x = x + self.pe[:, :seq_len, :]
        return self.dropout(x)
''')

    if needs_positional_embedding:
        helper_classes.append('''
class PositionalEmbedding(nn.Module):
    """Learned positional embeddings (BERT-style)."""

    def __init__(self, max_len: int, d_model: int):
        super().__init__()
        self.pos_embed = nn.Embedding(max_len, d_model)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        seq_len = x.size(1)
        positions = torch.arange(seq_len, device=x.device, dtype=torch.long)
        return x + self.pos_embed(positions).unsqueeze(0)
''')

    # Build layer definitions and forward logic
    layer_defs = []
    forward_lines = []
    layer_counter = {}

    def _layer_name(node_type: str) -> str:
        """Generate a unique layer variable name."""
        base = node_type.replace("2d", "_2d").replace("1d", "_1d")
        count = layer_counter.get(base, 0) + 1
        layer_counter[base] = count
        return f"{base}_{count}" if count > 1 else base

    # Map node_id -> variable name for forward pass
    var_map: dict[str, str] = {}
    layer_name_map: dict[str, str] = {}

    for idx, nid in enumerate(topo):
        node = nodes_by_id[nid]
        p = node.params
        src = get_input_node(graph, nid)
        in_shape = shapes.get(src) if src else None

        if node.type == "input" or node.type == "text_input":
            var_map[nid] = "x"
            continue

        if node.type == "output":
            src_var = var_map.get(src, "x") if src else "x"
            forward_lines.append(f"        return {src_var}")
            continue

        if node.type == "augment":
            src_var = var_map.get(src, "x") if src else "x"
            var_map[nid] = src_var
            continue

        src_var = var_map.get(src, "x") if src else "x"

        # Determine layer
        if node.type == "add":
            srcs = get_input_nodes(graph, nid)
            a_var = var_map.get(srcs[0], "x") if len(srcs) > 0 else "x"
            b_var = var_map.get(srcs[1], "x") if len(srcs) > 1 else "x"
            out_var = f"out_{idx}"
            var_map[nid] = out_var
            forward_lines.append(f"        {out_var} = {a_var} + {b_var}")
            continue

        if node.type == "concat":
            srcs = get_input_nodes(graph, nid)
            dim = int(p.get("dim", 1))
            vars_str = ", ".join(var_map.get(s, "x") for s in srcs)
            out_var = f"out_{idx}"
            var_map[nid] = out_var
            forward_lines.append(
                f"        {out_var} = torch.cat([{vars_str}], dim={dim})"
            )
            continue

        lname = _layer_name(node.type)
        layer_name_map[nid] = lname
        out_var = f"out_{idx}"
        var_map[nid] = out_var

        match node.type:
            case "linear":
                if in_shape and len(in_shape) == 3:
                    in_features = in_shape[-1]
                elif in_shape and len(in_shape) > 1:
                    in_features = math.prod(in_shape)
                elif in_shape:
                    in_features = in_shape[0]
                else:
                    in_features = 128
                out_features = int(p.get("out_features", 128))
                bias = bool(p.get("bias", True))
                layer_defs.append(
                    f"        self.{lname} = nn.Linear({in_features}, {out_features}, bias={bias})"
                )
                if in_shape and len(in_shape) == 3:
                    forward_lines.append(
                        f"        b, seq, d = {src_var}.shape"
                    )
                    forward_lines.append(
                        f"        {out_var} = self.{lname}({src_var}.reshape(-1, d)).reshape(b, seq, -1)"
                    )
                else:
                    forward_lines.append(
                        f"        {out_var} = self.{lname}({src_var}.flatten(1) if {src_var}.dim() > 2 else {src_var})"
                    )

            case "conv2d":
                in_channels = in_shape[0] if in_shape else 1
                out_channels = int(p.get("out_channels", 32))
                kernel_size = int(p.get("kernel_size", 3))
                stride = int(p.get("stride", 1))
                padding = int(p.get("padding", 0))
                layer_defs.append(
                    f"        self.{lname} = nn.Conv2d({in_channels}, {out_channels}, "
                    f"kernel_size={kernel_size}, stride={stride}, padding={padding})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "batchnorm":
                if in_shape and len(in_shape) >= 2:
                    num_features = in_shape[0]
                    bn_cls = "BatchNorm2d" if len(in_shape) >= 3 else "BatchNorm1d"
                elif in_shape:
                    num_features = in_shape[0]
                    bn_cls = "BatchNorm1d"
                else:
                    num_features = 32
                    bn_cls = "BatchNorm1d"
                layer_defs.append(
                    f"        self.{lname} = nn.{bn_cls}({num_features})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "layernorm":
                if in_shape:
                    ns = (in_shape[-1],) if len(in_shape) > 1 else tuple(in_shape)
                else:
                    ns = (128,)
                layer_defs.append(
                    f"        self.{lname} = nn.LayerNorm({list(ns)})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "dropout":
                drop_p = float(p.get("p", 0.5))
                layer_defs.append(
                    f"        self.{lname} = nn.Dropout(p={drop_p})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "relu":
                layer_defs.append(f"        self.{lname} = nn.ReLU()")
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "gelu":
                layer_defs.append(f"        self.{lname} = nn.GELU()")
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "sigmoid":
                layer_defs.append(f"        self.{lname} = nn.Sigmoid()")
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "tanh":
                layer_defs.append(f"        self.{lname} = nn.Tanh()")
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "maxpool2d":
                ks = int(p.get("kernel_size", 2))
                st = int(p.get("stride", 2))
                layer_defs.append(
                    f"        self.{lname} = nn.MaxPool2d(kernel_size={ks}, stride={st})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "maxpool1d":
                ks = int(p.get("kernel_size", 2))
                st = int(p.get("stride", 2))
                layer_defs.append(
                    f"        self.{lname} = nn.MaxPool1d(kernel_size={ks}, stride={st})"
                )
                forward_lines.append(
                    f"        # Transpose for MaxPool1d: (B, L, C) -> (B, C, L)"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var}.transpose(1, 2)).transpose(1, 2)"
                )

            case "flatten":
                layer_defs.append(
                    f"        self.{lname} = nn.Flatten(start_dim=1)"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "softmax":
                layer_defs.append(
                    f"        self.{lname} = nn.Softmax(dim=1)"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "embedding":
                num_emb = int(p.get("num_embeddings", 10000))
                emb_dim = int(p.get("embedding_dim", 128))
                layer_defs.append(
                    f"        self.{lname} = nn.Embedding({num_emb}, {emb_dim})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "positional_encoding":
                d_model = int(p.get("d_model", 128))
                max_len = int(p.get("max_len", 512))
                layer_defs.append(
                    f"        self.{lname} = PositionalEncoding({d_model}, max_len={max_len})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "positional_embedding":
                max_len = int(p.get("max_len", 512))
                d_model = int(p.get("d_model", 128))
                layer_defs.append(
                    f"        self.{lname} = PositionalEmbedding({max_len}, {d_model})"
                )
                forward_lines.append(
                    f"        {out_var} = self.{lname}({src_var})"
                )

            case "attention":
                embed_dim = int(p.get("embed_dim", 128))
                num_heads = int(p.get("num_heads", 4))
                layer_defs.append(
                    f"        self.{lname} = nn.MultiheadAttention("
                    f"embed_dim={embed_dim}, num_heads={num_heads}, batch_first=True)"
                )
                forward_lines.append(
                    f"        {out_var}, _ = self.{lname}({src_var}, {src_var}, {src_var})"
                )

            case _:
                forward_lines.append(
                    f"        {out_var} = {src_var}  # {node.type} (pass-through)"
                )

    # Assemble model class
    code_parts = imports.copy()
    for hc in helper_classes:
        code_parts.append(hc)

    code_parts.append("")
    code_parts.append("class Model(nn.Module):")
    code_parts.append(f'    """Neural network model exported from JulyAI."""')
    code_parts.append("")
    code_parts.append(f"    INPUT_SHAPE = {input_shape}  # Expected input shape (C, H, W) or (features,)")
    code_parts.append("")
    code_parts.append("    def __init__(self):")
    code_parts.append("        super().__init__()")

    if layer_defs:
        for ld in layer_defs:
            code_parts.append(ld)
    else:
        code_parts.append("        pass")

    code_parts.append("")
    code_parts.append("    def forward(self, x: torch.Tensor) -> torch.Tensor:")
    code_parts.append('        """Forward pass."""')

    if forward_lines:
        for fl in forward_lines:
            code_parts.append(fl)
    else:
        code_parts.append("        return x")

    # Build key map: node_id -> attribute name (for remapping DynamicModel state dicts)
    # DynamicModel saves as "layers.<node_id>.weight", exported model uses "self.<attr>.weight"
    key_map_dict = {}
    for nid, attr_name in layer_name_map.items():
        key_map_dict[nid] = attr_name

    code_parts.append("")
    code_parts.append("")
    code_parts.append("# Mapping from JulyAI runtime layer keys to exported model attribute names.")
    code_parts.append("# Used to load weights trained in JulyAI into this standalone model.")
    code_parts.append(f"_KEY_MAP = {repr(key_map_dict)}")
    code_parts.append("")
    code_parts.append("")
    code_parts.append("def remap_state_dict(state_dict: dict) -> dict:")
    code_parts.append('    """Remap state_dict keys from JulyAI DynamicModel format to exported model format.')
    code_parts.append("")
    code_parts.append('    JulyAI saves weights as "layers.<node_id>.weight/bias".')
    code_parts.append('    This model uses "self.<attr_name>.weight/bias".')
    code_parts.append('    """')
    code_parts.append("    remapped = {}")
    code_parts.append("    for key, value in state_dict.items():")
    code_parts.append("        new_key = key")
    code_parts.append('        if key.startswith("layers."):')
    code_parts.append('            parts = key.split(".", 2)  # ["layers", "<node_id>", "weight"]')
    code_parts.append("            if len(parts) >= 3:")
    code_parts.append("                node_id = parts[1]")
    code_parts.append("                param_suffix = parts[2]")
    code_parts.append("                if node_id in _KEY_MAP:")
    code_parts.append('                    new_key = f"{_KEY_MAP[node_id]}.{param_suffix}"')
    code_parts.append("        remapped[new_key] = value")
    code_parts.append("    return remapped")

    code_parts.append("")
    code_parts.append("")
    code_parts.append("def get_model(weights_path: str | None = None, device: str = 'cpu') -> Model:")
    code_parts.append('    """Create model and optionally load weights.')
    code_parts.append("")
    code_parts.append("    Automatically handles weights from JulyAI's runtime format")
    code_parts.append("    (DynamicModel) by remapping state_dict keys.")
    code_parts.append('    """')
    code_parts.append("    model = Model().to(device)")
    code_parts.append("    if weights_path:")
    code_parts.append("        state_dict = torch.load(weights_path, map_location=device, weights_only=True)")
    code_parts.append("        # Try direct load first; if keys mismatch, remap from JulyAI format")
    code_parts.append("        try:")
    code_parts.append("            model.load_state_dict(state_dict)")
    code_parts.append("        except RuntimeError:")
    code_parts.append("            remapped = remap_state_dict(state_dict)")
    code_parts.append("            model.load_state_dict(remapped)")
    code_parts.append('        print(f"Loaded weights from {weights_path}")')
    code_parts.append("    model.eval()")
    code_parts.append("    return model")
    code_parts.append("")
    code_parts.append("")
    code_parts.append("def count_parameters(model: nn.Module) -> int:")
    code_parts.append('    """Count trainable parameters."""')
    code_parts.append(
        "    return sum(p.numel() for p in model.parameters() if p.requires_grad)"
    )
    code_parts.append("")
    code_parts.append("")
    code_parts.append('if __name__ == "__main__":')
    code_parts.append("    model = Model()")
    code_parts.append(f'    print("Model architecture:")')
    code_parts.append("    print(model)")
    code_parts.append(f'    print(f"\\nTotal trainable parameters: {{count_parameters(model):,}}")')
    code_parts.append(f"    x = torch.randn(1, *Model.INPUT_SHAPE)")
    code_parts.append("    with torch.no_grad():")
    code_parts.append("        y = model(x)")
    code_parts.append(f'    print(f"Forward pass: {{list(x.shape)}} -> {{list(y.shape)}}")')
    code_parts.append("")

    return "\n".join(code_parts)


