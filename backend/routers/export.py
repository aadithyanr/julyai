@router.post("/api/export/package")
async def export_package(request: ExportRequest):
    """Generate and download a standalone Python project ZIP.

    Includes model.py, predict.py, train.py, test_model.py, data_loader.py,
    model_manager.py, config.json, requirements.txt, README.md, and sample data.

    If playground_id is provided, includes ALL trained models for that playground.
    If model_id is provided, includes that specific model's weights.
    """
    try:
        # Normalize graph
        graph = normalize_graph(request.graph)

        # Infer shapes
        input_shape = _get_input_shape(graph)
        try:
            shapes = infer_shapes(graph, tuple(input_shape))
        except Exception as e:
            logger.warning("Shape inference failed, using defaults: %s", e)
            shapes = {}

        num_classes = _get_num_classes(graph, shapes)
        model_name = graph.metadata.name or "JulyAI Model"

        # Collect trained models
        models_info: list[dict] = []
        weight_files: list[tuple[str, bytes]] = []  # (filename, bytes)

        # If playground_id provided, get ALL trained models
        if request.playground_id:
            try:
                playground_models = list_playground_models(request.playground_id)
                for idx, pm in enumerate(playground_models):
                    model_id = pm["id"]
                    info = {
                        "id": model_id,
                        "name": pm.get("name", f"model_v{idx + 1}"),
                        "accuracy": pm.get("final_accuracy"),
                        "loss": pm.get("final_loss"),
                        "created_at": pm.get("created_at"),
                    }
                    # Try to download weights
                    try:
                        state_dict_b64 = get_model_state_dict(model_id)
                        weight_bytes = base64.b64decode(state_dict_b64)
                        safe_name = pm.get("name", f"model_v{idx + 1}").replace(" ", "_").replace("/", "_")
                        filename = f"model_{safe_name}.pt"
                        weight_files.append((filename, weight_bytes))
                        info["weights_file"] = f"weights/{filename}"
                    except Exception as e:
                        logger.warning("Failed to download weights for model %s: %s", model_id, e)
                        info["weights_file"] = None
                        info["weights_error"] = str(e)
                    models_info.append(info)
            except Exception as e:
                logger.warning("Failed to list playground models: %s", e)

        # If specific model_id, also add it (if not already included)
        if request.model_id:
            already_included = any(m["id"] == request.model_id for m in models_info)
            if not already_included:
                try:
                    model_data = get_model_from_db(request.model_id)
                    info = {
                        "id": request.model_id,
                        "name": model_data.get("name", "model"),
                        "accuracy": model_data.get("final_accuracy"),
                        "loss": model_data.get("final_loss"),
                        "created_at": model_data.get("created_at"),
                    }
                    try:
                        state_dict_b64 = get_model_state_dict(request.model_id)
                        weight_bytes = base64.b64decode(state_dict_b64)
                        weight_files.append(("model_v1.pt", weight_bytes))
                        info["weights_file"] = "weights/model_v1.pt"
                    except Exception as e:
                        info["weights_file"] = None
                        info["weights_error"] = str(e)
                    models_info.append(info)
                except Exception as e:
                    logger.warning("Failed to get model %s: %s", request.model_id, e)

        has_weights = len(weight_files) > 0

        # Generate all files
        model_code = _generate_model_code(graph, shapes)
        predict_code = _generate_predict_code(input_shape, num_classes)
        train_code = _generate_train_code(input_shape, num_classes)
        test_code = _generate_test_code(input_shape, num_classes)
        data_loader_code = _generate_data_loader_code(input_shape)
        model_manager_code = _generate_model_manager_code()
        readme = _generate_readme(
            input_shape, num_classes, model_name, has_weights, len(weight_files)
        )
        requirements = _generate_requirements()
        config = _generate_config(graph, input_shape, num_classes, models_info)
        sample_input = _generate_sample_input(input_shape)

        # Create ZIP in memory
        buffer = io.BytesIO()
        with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as zf:
            prefix = "julyai-model/"
            zf.writestr(f"{prefix}model.py", model_code)
            zf.writestr(f"{prefix}predict.py", predict_code)
            zf.writestr(f"{prefix}train.py", train_code)
            zf.writestr(f"{prefix}test_model.py", test_code)
            zf.writestr(f"{prefix}data_loader.py", data_loader_code)
            zf.writestr(f"{prefix}model_manager.py", model_manager_code)
            zf.writestr(f"{prefix}requirements.txt", requirements)
            zf.writestr(f"{prefix}README.md", readme)
            zf.writestr(f"{prefix}config.json", config)
            zf.writestr(f"{prefix}sample_data/sample_input.json", sample_input)

            # Add weight files
            for filename, wbytes in weight_files:
                zf.writestr(f"{prefix}weights/{filename}", wbytes)

            # If no weights, create empty weights dir marker
            if not weight_files:
                zf.writestr(f"{prefix}weights/.gitkeep", "")

        buffer.seek(0)

        safe_name = (model_name or "model").replace(" ", "-").lower()
        filename = f"julyai-{safe_name}.zip"

        logger.info(
            "Export package generated: %s (%d files, %d weights, %.1f KB)",
            filename,
            10 + len(weight_files),
            len(weight_files),
            buffer.getbuffer().nbytes / 1024,
        )

        return StreamingResponse(
            buffer,
            media_type="application/zip",
            headers={"Content-Disposition": f"attachment; filename={filename}"},
        )

    except Exception as e:
        logger.exception("Failed to generate export package: %s", e)
        raise HTTPException(status_code=500, detail=str(e))
