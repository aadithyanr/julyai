def _generate_config(
    graph: GraphSchema,
    input_shape: list[int],
    num_classes: int,
    models_info: list[dict],
) -> str:
    """Generate config.json with model metadata."""
    nodes_summary = []
    for n in graph.nodes:
        nodes_summary.append({
            "id": n.id,
            "type": n.type,
            "params": n.params,
        })

    config = {
        "model_name": graph.metadata.name or "JulyAI Model",
        "generated_at": datetime.utcnow().isoformat(),
        "input_shape": input_shape,
        "num_classes": num_classes,
        "architecture": {
            "nodes": nodes_summary,
            "node_count": len(graph.nodes),
            "edge_count": len(graph.edges),
        },
        "trained_models": models_info,
        "training_defaults": {
            "epochs": 10,
            "batch_size": 64,
            "learning_rate": 0.001,
            "optimizer": "adam",
        },
    }
    return json.dumps(config, indent=2)


def _generate_sample_input(input_shape: list[int]) -> str:
    """Generate a sample JSON input file."""
    import random
    random.seed(42)
    total_features = 1
    for s in input_shape:
        total_features *= s
    # Create a flat tensor and reshape info
    sample = {
        "description": "Sample input tensor for testing. Generated by JulyAI.",
        "input_shape": input_shape,
        "input": [[random.gauss(0, 1) for _ in range(total_features)]],
    }
    return json.dumps(sample, indent=2)


