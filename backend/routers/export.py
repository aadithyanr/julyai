def list_models(weights_dir: str = "weights") -> list[dict]:
    """List all saved model weights with metadata."""
    wdir = Path(weights_dir)
    if not wdir.exists():
        print("No weights directory found. Train a model first: python train.py")
        return []

    models = []
    for pt_file in sorted(wdir.glob("*.pt")):
        info = {
            "file": str(pt_file),
            "name": pt_file.stem,
            "size_mb": round(pt_file.stat().st_size / (1024 * 1024), 2),
        }

